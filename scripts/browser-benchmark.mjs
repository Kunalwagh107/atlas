/**
 * Real-browser performance measurements for Atlas.
 *
 * Programmatically builds the app, starts Vite preview, drives the built app in
 * Playwright Chromium, imports a deterministic large-map fixture THROUGH THE
 * REAL "Import JSON" FILE INPUT, and measures:
 *   (a) file-input change -> first real `.map-node` rendered in the DOM
 *   (b) node-title edit: keystroke input latency + Enter -> node text in DOM
 *   (c) pointer-drag frame times (requestAnimationFrame deltas during a drag)
 *
 * Outputs:
 *   scripts/.browser-bench-results.json  (compact machine-readable result)
 *   BENCHMARKS.md                         (clearly marked browser section)
 *
 * Windows Git Bash safe. The preview server, browser and temporary build dir
 * are always torn down in finally blocks — no detached processes are left.
 * If Chromium or the build is unavailable the script SKIPS with a clear
 * message instead of failing.
 *
 *   Run: node scripts/browser-benchmark.mjs
 *   Env: BROWSER_BENCH_NODES (default 2000, range 100..20000)
 *        PLAYWRIGHT_CHANNEL (chrome | msedge | bundled | chromium)
 */
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';
import { build, createServer, preview } from 'vite';

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, '..');
const RESULTS = resolve(HERE, '.browser-bench-results.json');
const BENCH = resolve(ROOT, 'BENCHMARKS.md');
const DIST = resolve(HERE, '.browser-bench-dist');
const MARK_START = '<!-- BROWSER-BENCH:START -->';
const MARK_END = '<!-- BROWSER-BENCH:END -->';

const NODE_COUNT = readNodeCount(process.env.BROWSER_BENCH_NODES);

function readNodeCount(raw) {
  const n = Number(raw);
  return Number.isFinite(n) && n >= 100 && n <= 20000 ? Math.round(n) : 2000;
}
function toPosix(p) {
  return p.split('\\').join('/');
}
function round(n) {
  return Number.isFinite(n) ? Math.round(n * 100) / 100 : null;
}
function median(values) {
  if (!values.length) return 0;
  const s = [...values].sort((a, b) => a - b);
  const m = Math.floor(s.length / 2);
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
}
function percentile(values, p) {
  if (!values.length) return 0;
  const s = [...values].sort((a, b) => a - b);
  const i = Math.min(s.length - 1, Math.ceil((p / 100) * s.length) - 1);
  return s[Math.max(0, i)];
}

/** Mirror playwright.config.ts: prefer bundled Chromium, else a system channel. */
function resolveChannel() {
  const explicit = process.env.PLAYWRIGHT_CHANNEL;
  if (explicit === 'chrome' || explicit === 'msedge') return explicit;
  if (explicit === 'bundled' || explicit === 'chromium') return undefined;
  try {
    if (existsSync(chromium.executablePath())) return undefined;
  } catch {
    /* executablePath can throw before browsers are resolved — treat as missing */
  }
  return 'chrome';
}

/** Build the fixture with the app's own generator + serializer (no schema drift). */
async function makeFixtureJson() {
  const server = await createServer({
    configFile: false,
    root: toPosix(ROOT),
    server: { middlewareMode: true },
    appType: 'custom',
    logLevel: 'error',
    // Only used to SSR-load two plain TS modules; skip the browser dep scan.
    optimizeDeps: { noDiscovery: true, include: [] },
  });
  try {
    const fixtures = await server.ssrLoadModule('/src/test/fixtures.ts');
    const json = await server.ssrLoadModule('/src/export/json.ts');
    return json.documentToJson(fixtures.makeLargeDoc(NODE_COUNT));
  } finally {
    await server.close();
  }
}

function writeResults(payload) {
  writeFileSync(RESULTS, `${JSON.stringify(payload, null, 2)}\n`, 'utf8');
}

/** Replace any prior marked browser section so repeat runs stay clean. */
function writeBrowserSection(markdown) {
  let text = existsSync(BENCH) ? readFileSync(BENCH, 'utf8') : '# Atlas performance benchmarks\n';
  const start = text.indexOf(MARK_START);
  const end = text.indexOf(MARK_END);
  if (start !== -1 && end > start) text = text.slice(0, start) + text.slice(end + MARK_END.length);
  text = text.replace(/\s+$/, '') + '\n\n' + MARK_START + '\n' + markdown.trim() + '\n' + MARK_END + '\n';
  writeFileSync(BENCH, text, 'utf8');
}

function resultsToMarkdown(r) {
  if (r.skipped) {
    return [
      '## Real-browser measurements (Chromium + Vite preview)',
      '',
      `**Skipped:** ${r.reason}`,
      '',
      'No browser numbers were produced for this run; the offline Node / Vite SSR',
      'table above still applies to pure computation only.',
    ].join('\n');
  }
  const m = r.metrics;
  return [
    '## Real-browser measurements (Chromium + Vite preview)',
    '',
    `Generated by \`node scripts/browser-benchmark.mjs\` on ${r.generatedAt} · ${r.browser} · fixture: **${r.nodeCount} nodes**, imported through the real "Import JSON" file input.`,
    '',
    'These are end-to-end browser numbers (parse + layout + paint + input dispatch).',
    'They are **not directly comparable** with the offline Node / Vite SSR table above,',
    'which measures pure computation only.',
    '',
    '| Metric | Value |',
    '| --- | ---: |',
    `| Import → first nodes rendered in DOM (file-input change → \`.map-node\` present) | ${m.importToDomMs} ms |`,
    `| Nodes present in DOM after fit-to-view | ${m.domNodesAfterImport} (fixture: ${r.nodeCount}) |`,
    `| Node-title edit — first key → first \`input\` event | ${m.firstKeyToInputMs} ms |`,
    `| Node-title edit — mean interval between keystrokes | ${m.meanKeyIntervalMs} ms (${m.keystrokes} keys) |`,
    `| Node-title edit — Enter → committed title rendered in DOM | ${m.commitToRenderMs} ms |`,
    `| Pointer drag — rAF frame deltas sampled | ${m.dragFrames} |`,
    `| Pointer drag — median frame | ${m.dragMedianFrameMs} ms |`,
    `| Pointer drag — p95 frame | ${m.dragP95FrameMs} ms |`,
    `| Pointer drag — frames over 33 ms | ${m.dragLongFrames} of ${m.dragFrames} |`,
    '',
    'Method: a MutationObserver timestamps the file-input `change` event and the first',
    '`.map-node` insertion; keydown/input listeners on the inline editor timestamp typing;',
    'a MutationObserver timestamps the commit becoming visible (editor unmount / title in the SVG node); rAF deltas are',
    'sampled while pointer moves are paced at ~16 ms so each frame carries one move. Drag frame',
    'times are browser render cadence under a paced pointer drag, not isolated app render time.',
  ].join('\n');
}

let previewServer;
let browser;
try {
  const channel = resolveChannel();
  const channelLabel = channel ? `Chromium channel "${channel}"` : 'bundled Chromium';
  const fixtureJson = await makeFixtureJson();

  // Fresh build into a throwaway dir so we measure current src without
  // disturbing the repository's normal `dist` or team members' builds.
  await build({
    root: toPosix(ROOT),
    configFile: toPosix(resolve(ROOT, 'vite.config.ts')),
    logLevel: 'error',
    build: { outDir: toPosix(DIST), emptyOutDir: true },
  });
  previewServer = await preview({
    root: toPosix(ROOT),
    configFile: toPosix(resolve(ROOT, 'vite.config.ts')),
    logLevel: 'error',
    build: { outDir: toPosix(DIST) },
    preview: { host: '127.0.0.1', port: 0, strictPort: false },
  });
  const address = previewServer.httpServer.address();
  const port = address && typeof address === 'object' ? address.port : 4173;
  const url = `http://127.0.0.1:${port}/`;

  try {
    browser = await chromium.launch({ channel, headless: true });
  } catch (err) {
    const reason = `Chromium unavailable (${channelLabel}): ${String(err?.message ?? err).split('\n')[0]}`;
    const payload = { generatedAt: new Date().toISOString(), nodeCount: NODE_COUNT, browser: channelLabel, skipped: true, reason };
    writeResults(payload);
    writeBrowserSection(resultsToMarkdown(payload));
    console.log(`[browser-bench] SKIPPED — ${reason}`);
    process.exitCode = 0;
  }

  if (browser) {
    const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
    const consoleErrors = [];
    page.on('pageerror', (e) => consoleErrors.push(e.message));
    page.on('console', (m) => { if (m.type() === 'error') consoleErrors.push(m.text()); });

    const metrics = {};
    try {
      await page.goto(url, { waitUntil: 'load' });
      // Fresh context => empty IndexedDB => the empty state is shown.
      await page.getByRole('button', { name: /Create Blank Map/i }).waitFor({ timeout: 20_000 });
      await page.getByRole('button', { name: /Import JSON/i }).first().click();
      const dialog = page.getByRole('dialog', { name: /Import a mind map/i });
      await dialog.waitFor({ timeout: 10_000 });
      const fileInput = dialog.locator('input[type="file"]');

      // Install in-page markers BEFORE handing the file to the app.
      await page.evaluate(() => {
        const dlg = document.querySelector('[role="dialog"]');
        const input = dlg?.querySelector('input[type="file"]');
        window.__benchImport = { start: performance.now(), changeAt: null, nodesAt: null, domNodes: 0 };
        input?.addEventListener('change', () => { window.__benchImport.changeAt = performance.now(); }, { once: true });
        const obs = new MutationObserver(() => {
          if (window.__benchImport.nodesAt !== null) return;
          const count = document.querySelectorAll('.map-node').length;
          if (count > 1) {
            window.__benchImport.nodesAt = performance.now();
            window.__benchImport.domNodes = count;
          }
        });
        obs.observe(document.body, { childList: true, subtree: true });
      });

      await fileInput.setInputFiles({
        name: 'atlas-bench-map.json',
        mimeType: 'application/json',
        buffer: Buffer.from(fixtureJson, 'utf8'),
      });
      await page.waitForFunction(() => window.__benchImport?.nodesAt !== null, null, { timeout: 60_000 });
      const imp = await page.evaluate(() => ({
        changeAt: window.__benchImport.changeAt,
        start: window.__benchImport.start,
        nodesAt: window.__benchImport.nodesAt,
        domNodes: window.__benchImport.domNodes,
        finalDomNodes: document.querySelectorAll('.map-node').length,
        liveRegion: document.querySelector('.sr-only[aria-live]')?.textContent ?? '',
      }));
      metrics.importToDomMs = round(imp.nodesAt - (imp.changeAt ?? imp.start));
      metrics.domNodesAfterImport = imp.finalDomNodes || imp.domNodes;
      metrics.visibleNodesAnnounced = imp.liveRegion.trim() || null;

      // (b) Node-title editing latency. Use the root node: viewport culling can
      // drop deeper nodes from the DOM at fit-to-view, but the root is always
      // rendered (and selected) after the import.
      const nodeButton = page.locator('.map-node.is-root [role="button"]').first();
      await nodeButton.waitFor({ timeout: 15_000 });
      await nodeButton.dblclick();
      const editor = page.getByLabel('Edit node title');
      await editor.waitFor({ timeout: 10_000 });
      // The editor mounts with the text selected; force selection to be safe.
      await editor.evaluate((el) => { el.focus(); el.select(); });

      // Short title: SVG node text is wrapped/truncated, so exact text matching
      // is unreliable. The commit signal is the editor unmounting after Enter.
      const newTitle = `B${Date.now() % 100000}`;
      await page.evaluate((expected) => {
        const el = document.querySelector('[aria-label="Edit node title"]');
        window.__benchTyping = { downs: [], inputs: [], commitDown: null, renderAt: null };
        el?.addEventListener('keydown', (e) => {
          window.__benchTyping.downs.push({ key: e.key, t: performance.now() });
          if (e.key === 'Enter' && window.__benchTyping.commitDown === null) {
            window.__benchTyping.commitDown = performance.now();
          }
        }, true);
        el?.addEventListener('input', () => { window.__benchTyping.inputs.push(performance.now()); }, true);
        const target = document.querySelector('.map-node.is-root');
        const obs = new MutationObserver(() => {
          if (window.__benchTyping.renderAt !== null) return;
          const committed = el && !el.isConnected; // editor unmounted on commit
          const textUpdated = target && target.textContent && target.textContent.includes(expected);
          if (committed || textUpdated) window.__benchTyping.renderAt = performance.now();
        });
        obs.observe(document.body, { childList: true, subtree: true, characterData: true });
      }, newTitle);

      await page.keyboard.type(newTitle);
      await page.keyboard.press('Enter');
      await page.waitForFunction(() => window.__benchTyping?.renderAt !== null, null, { timeout: 15_000 });
      const t = await page.evaluate(() => window.__benchTyping);
      const printable = t.downs.find((d) => d.key.length === 1);
      const inputs = t.inputs;
      metrics.firstKeyToInputMs = round(inputs.length && printable ? inputs[0] - printable.t : 0);
      metrics.meanKeyIntervalMs = round(inputs.length > 1 ? (inputs[inputs.length - 1] - inputs[0]) / (inputs.length - 1) : 0);
      metrics.keystrokes = inputs.length;
      metrics.commitToRenderMs = round(t.renderAt - (t.commitDown ?? t.renderAt));

      // (c) Pointer-drag frame times via requestAnimationFrame.
      const dragNode = page.locator('.map-node.is-root [role="button"]').first();
      await dragNode.click(); // ensure the node is selected before dragging
      const box = await dragNode.boundingBox();
      if (!box) throw new Error('Could not read node bounding box for drag');
      await page.evaluate(() => {
        window.__benchFrames = [];
        window.__benchStopFrames = false;
        let last = performance.now();
        const tick = (now) => {
          if (window.__benchStopFrames) return;
          window.__benchFrames.push(now - last);
          last = now;
          requestAnimationFrame(tick);
        };
        requestAnimationFrame(tick);
      });
      const sx = box.x + box.width / 2;
      const sy = box.y + box.height / 2;
      const dragFrames = 60;
      await page.mouse.move(sx, sy);
      await page.mouse.down();
      for (let i = 1; i <= dragFrames; i++) {
        await page.mouse.move(sx + (i / dragFrames) * 160, sy + (i / dragFrames) * 100);
        await page.waitForTimeout(16); // pace ~one pointer move per frame
      }
      await page.mouse.up();
      const frames = await page.evaluate(() => {
        window.__benchStopFrames = true;
        return window.__benchFrames.slice(2); // drop warm-up frames
      });
      metrics.dragFrames = frames.length;
      metrics.dragMedianFrameMs = round(median(frames));
      metrics.dragP95FrameMs = round(percentile(frames, 95));
      metrics.dragLongFrames = frames.filter((f) => f > 33).length;

      const payload = {
        generatedAt: new Date().toISOString(),
        nodeCount: NODE_COUNT,
        browser: channelLabel,
        skipped: false,
        consoleErrors,
        metrics,
      };
      writeResults(payload);
      writeBrowserSection(resultsToMarkdown(payload));
      console.log('[browser-bench] results:');
      console.log(JSON.stringify(payload, null, 2));
    } catch (err) {
      const reason = `Measurement failed: ${String(err?.message ?? err).split('\n')[0]}`;
      const payload = {
        generatedAt: new Date().toISOString(),
        nodeCount: NODE_COUNT,
        browser: channelLabel,
        skipped: true,
        reason,
        partial: metrics,
      };
      writeResults(payload);
      writeBrowserSection(resultsToMarkdown(payload));
      console.log(`[browser-bench] SKIPPED — ${reason}`);
    }
  }
} catch (err) {
  const reason = `Setup failed: ${String(err?.message ?? err).split('\n')[0]}`;
  const payload = { generatedAt: new Date().toISOString(), nodeCount: NODE_COUNT, skipped: true, reason };
  writeResults(payload);
  writeBrowserSection(resultsToMarkdown(payload));
  console.log(`[browser-bench] SKIPPED — ${reason}`);
} finally {
  if (browser) await browser.close().catch(() => {});
  if (previewServer) await previewServer.close().catch(() => {});
  rmSync(DIST, { recursive: true, force: true });
}
